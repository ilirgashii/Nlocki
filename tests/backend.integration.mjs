import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { idlFactory } from '../src/frontend/src/declarations/backend.did.js';
const requireFrontend = createRequire(new URL('../src/frontend/package.json', import.meta.url));
const { Actor, HttpAgent, AnonymousIdentity } = requireFrontend('@icp-sdk/core/agent');
const { Ed25519KeyIdentity } = requireFrontend('@icp-sdk/core/identity');
const dfx = process.env.NLOCKI_DFX || 'dfx';
const canisterId = process.env.NLOCKI_CANISTER_ID || execFileSync(dfx, ['canister', 'id', 'backend'], { encoding: 'utf8' }).trim();
async function actor(identity) {
  const agent = new HttpAgent({ identity, host: process.env.NLOCKI_BACKEND_HOST || 'http://127.0.0.1:4943' });
  await agent.fetchRootKey();
  return Actor.createActor(idlFactory, { agent, canisterId });
}
const aliceIdentity = Ed25519KeyIdentity.generate(), bobIdentity = Ed25519KeyIdentity.generate(), carolIdentity = Ed25519KeyIdentity.generate();
const aliceId = aliceIdentity.getPrincipal().toText(), bobId = bobIdentity.getPrincipal().toText();
const alice = await actor(aliceIdentity), bob = await actor(bobIdentity), carol = await actor(carolIdentity), anon = await actor(new AnonymousIdentity());
const username = `u_${aliceId.replaceAll('-', '').slice(0, 18)}`;
const date = '2020-01-02';
let workout, meal, post, message;
await test('authenticated profiles, unique usernames and private contact details', async () => {
  await assert.rejects(anon.addTask(date, 'Not permitted'), /Sign in required/);
  await assert.rejects(anon.getTasksForDate(date), /Sign in required/);
  await alice.createOrGetProfile(); await bob.createOrGetProfile(); await carol.createOrGetProfile();
  const p = await alice.updateProfile([username], ['private@example.test'], ['123456789'], ['Private bio'], ['Alice'], [false]);
  assert.equal(p.userId, aliceId); assert.equal(p.email[0], 'private@example.test');
  await assert.rejects(bob.updateProfile([username.toUpperCase()], [], [], [], [], []), /already in use/);
  const publicSearch = await bob.searchUsers(username);
  assert.equal(publicSearch.length, 1); assert.deepEqual(publicSearch[0].email, []); assert.deepEqual(publicSearch[0].phone, []); assert.equal(publicSearch[0].bio, '');
  assert.deepEqual((await bob.getProfile(aliceId))[0].email, []);
});
await test('task CRUD is isolated between users', async () => {
  const t = await alice.addTask(date, 'Real persisted task');
  assert.equal((await alice.getTasksForDate(date)).length, 1);
  assert.deepEqual(await bob.getTasksForDate(date), []);
  assert.equal(await bob.toggleTask(t.id), false);
  assert.equal(await alice.toggleTask(t.id), true);
  assert.equal((await alice.getTasksForDate(date))[0].completed, true);
  assert.equal(await alice.deleteTask(t.id), true);
  assert.deepEqual(await alice.getTasksForDate(date), []);
  await alice.addTask(date, 'Survives restart');
});
await test('workout editing keeps its ID and meal metadata survives server storage', async () => {
  workout = await alice.addWorkout({ date, exerciseName: 'Squat', sets: 3n, reps: 8n, weight: [50], details: [JSON.stringify({ durationMin: 30, caloriesBurned: 120, notes: 'Real notes' })] });
  const edited = await alice.updateWorkout(workout.id, { date, exerciseName: 'Squat', sets: 4n, reps: 10n, weight: [60], details: workout.details });
  assert.equal(edited[0].id, workout.id); assert.equal(edited[0].sets, 4n);
  assert.deepEqual(await bob.getWorkoutsForDate(date), []);
  assert.deepEqual(await bob.updateWorkout(workout.id, { date, exerciseName: 'Stolen', sets: 1n, reps: 1n, weight: [], details: [] }), []);
  meal = await alice.addMeal({ date, mealName: 'Oats', calories: 300n, protein: 12n, carbs: 40n, fat: 6n, details: [JSON.stringify({ mealType: 'breakfast', notes: 'With milk', proteinG: 12.5 })] });
  assert.equal(JSON.parse((await alice.getMealsForDate(date))[0].details[0]).mealType, 'breakfast');
  assert.deepEqual(await bob.getMealsForDate(date), []);
  assert.equal((await alice.getWorkoutStreak()).currentStreak, 0n);
});
